import { readFile, writeFile } from 'node:fs/promises';
import { Script } from 'node:vm';

// shortcut: these modules only use named imports/exports; use a bundler if that changes.
export async function bundle() {
  const names = ['engine', 'cpu', 'session', 'controls', 'presentation', 'pixels', 'render', 'audio', 'main'];
  const sources = await Promise.all(names.map(name => readFile(new URL(`../src/${name}.js`, import.meta.url), 'utf8')));
  const body = sources.map((source, index) => `// src/${names[index]}.js\n${source
    .replace(/^import \{[^\n]+\} from ['"]\.\/[a-z-]+\.js['"];?\r?\n/gm, '')
    .replace(/^export (?=(?:const|function|class) )/gm, '')}`).join('\n\n');
  const result = `// Generated by npm run bundle. Edit src/ files instead.\n(() => {\n'use strict';\n${body}\n})();\n`;
  new Script(result, { filename: 'game.js' });
  const target = new URL('../game.js', import.meta.url);
  const existing = await readFile(target, 'utf8').catch(error => { if (error.code !== 'ENOENT') throw error; return null; });
  if (existing !== result) await writeFile(target, result);
  return result;
}
await bundle();
